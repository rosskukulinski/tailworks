package gen

import (
	"fmt"
	"strings"

	"github.com/rosskukulinski/tailworks/hostd/bundle"
)

// RPC into a Python Worker (issue #430, ADR-055).
//
// A service binding's RPC call reaches the front's __tw_binding entrypoint,
// whose dispatcher (runtime.ts bindingDispatcher) seals the caller and
// refuses handler names, then hands the call to the front's default
// export's Symbol.for("tailworks.pyRpc") function. That calls
// TailworksRpc.call() in tenant-py over the front's __TW_PY_RPC binding,
// with the entrypoint, method, arguments and the call's sealed cf (as
// JSON, without the create ticket).
//
// TailworksRpc lives in tenant-py's main module, which is generated
// (pyMainSource): it re-exports the app's main module, so workerd sees the
// app's classes and handlers as before, and adds TailworksRpc. call()
// finds the entrypoint class (Default, or a named WorkerEntrypoint
// subclass) and the method (a public function on the class, not a handler
// name), sets ctx.cf to the call's cf, so get_caller(self.ctx) names the
// caller as getCaller(this.ctx) does in JavaScript, and runs the method on
// a new instance. Only the front has a binding to TailworksRpc; a caller
// naming it as an entrypoint is refused.

// pyMainModule is tenant-py's generated main module.
const pyMainModule = "_tw_main.py"

// pyRPCEntrypoint is the class in pyMainModule the front calls.
const pyRPCEntrypoint = "TailworksRpc"

const pyMainSource = `# Generated by tw-hostd: the main module of a Python Worker's Python side.
# It re-exports the app's main module, and adds TailworksRpc, the entrypoint
# the JavaScript front forwards RPC calls to (ADR-055, issue #430).
import importlib as _tw_importlib
from inspect import isawaitable as _tw_isawaitable, isclass as _tw_isclass
from types import FunctionType as _tw_FunctionType

import js as _tw_js
from workers import WorkerEntrypoint as _TwWorkerEntrypoint

_tw_main = _tw_importlib.import_module(%[1]q)
if hasattr(_tw_main, "TailworksRpc"):
    raise ImportError("tailworks: TailworksRpc is a reserved name in a Python Worker's main module")
_tw_public = (
    list(_tw_main.__all__)
    if hasattr(_tw_main, "__all__")
    else [k for k in dir(_tw_main) if not k.startswith("_")]
)
for _tw_k in set(_tw_public) | {k for k in dir(_tw_main) if not k.startswith("_")}:
    globals()[_tw_k] = getattr(_tw_main, _tw_k)
if hasattr(_tw_main, "__all__"):
    __all__ = [*_tw_public, "TailworksRpc"]

# Workers handler names: not callable over RPC (runtime.ts HANDLER_METHODS).
_TW_HANDLERS = frozenset((
    "alarm",
    "connect",
    "email",
    "fetch",
    "pubsub",
    "queue",
    "scheduled",
    "tail",
    "tailStream",
    "test",
    "trace",
    "webSocketClose",
    "webSocketError",
    "webSocketMessage",
))


def _tw_entrypoint(name):
    cls = globals().get(name) if name in _tw_public else None
    if not (_tw_isclass(cls) and issubclass(cls, _TwWorkerEntrypoint)) or cls is TailworksRpc or cls is _TwWorkerEntrypoint:
        return None
    return cls


def _tw_method(cls, name):
    # What workerd offers over RPC: a public function defined on the class.
    if not isinstance(name, str) or name.startswith("_") or name in _TW_HANDLERS:
        return None
    for base in cls.__mro__:
        if name in base.__dict__:
            return base.__dict__[name] if isinstance(base.__dict__[name], _tw_FunctionType) else None
    return None


class TailworksRpc(_TwWorkerEntrypoint):
    async def call(self, entrypoint, method, args, cf):
        ep = entrypoint or "Default"
        cls = _tw_entrypoint(ep) if entrypoint != "Default" else None
        if cls is None:
            if entrypoint:
                raise TypeError(f"this workload's main module exports no entrypoint {entrypoint}")
            raise TypeError("this Python Worker has no Default WorkerEntrypoint class; RPC needs one")
        if _tw_method(cls, method) is None:
            raise TypeError(f'The RPC receiver does not implement the method "{method}".')
        ctx = self._tw_ctx
        # get_caller(self.ctx): the caller, as request.cf names it in fetch().
        ctx.cf = _tw_js.JSON.parse(cf)
        inst = cls(ctx, self._tw_env)
        r = getattr(inst, method)(*(args or []))
        if _tw_isawaitable(r):
            r = await r
        return r


def _tw_init(self, ctx, env):
    # The JavaScript ctx and env as workerd passes them: the app's class
    # wraps them itself when call() constructs it.
    self._tw_ctx = ctx
    self._tw_env = env


TailworksRpc.__init__ = _tw_init
`

// pyMain is tenant-py's generated main module for py.
func pyMain(py *bundle.App) ([]byte, error) {
	name := strings.TrimSuffix(py.PythonModuleName(py.Main), ".py")
	if name == "" || strings.Contains(name, "/") {
		return nil, fmt.Errorf("gen: Python main module %s is not at its directory's top", py.Main)
	}
	if _, ok := py.Modules[py.PythonBase()+pyMainModule]; ok {
		return nil, fmt.Errorf("gen: %s is a reserved module name in a Python Worker", pyMainModule)
	}
	return []byte(fmt.Sprintf(pyMainSource, name)), nil
}

// pythonFrontRPCBinding is the front's binding to tenant-py's TailworksRpc.
func pythonFrontRPCBinding() string {
	return fmt.Sprintf("    (name = \"__TW_PY_RPC\", service = (name = \"tenant-py\", entrypoint = %s)),\n", cq(pyRPCEntrypoint))
}
