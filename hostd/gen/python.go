// Python Workers (ADR-055, docs/python.md).
//
// workerd can't import a Python module from JavaScript, so the usual
// wrap-by-import (__tw_main.js imports the tenant's main) can't wrap a
// Python Worker. Instead the instance gets one more worker, "tenant-py",
// holding the Python modules, and the "tenant" worker becomes a generated
// JavaScript front (pythonFrontJS) whose default export forwards each
// request to it over a service binding. The front is wrapped by
// __tw_main.js like any JavaScript Worker, so the caller seal is checked
// (request.cf.tailscale.caller is the verified caller, or absent), public
// and tailnet requests are told apart, and requests are traced, at one
// enforcement point shared with JavaScript Workers. Only the front can
// reach tenant-py: no socket and no other binding names it.
//
// tenant-py has the app's own bindings (vars, secrets, KV/D1/R2, service
// bindings, its Durable Object namespaces) and the tenant's egress. Its
// Durable Objects are plain-DO internal objects (bundle.finishPython): no
// node, so nothing for create admission to mint, and no ctx.tailnet.

// pythonFrontModule is the front's main module (in the front's view of
// the app).
const pythonFrontModule = "__tw_py.js"

const pythonFrontJS = `// Generated by tw-hostd: the JavaScript front of a Python Worker.
// __tw_main.js wraps this default export (seal, public/tailnet, traces, the
// cron run's controller, the queue batch's ticket).
export default {
  fetch(req, env) {
    return env.__TW_PY.fetch(req);
  },
  // A cron run: the Python default export's scheduled(), through workerd's
  // Fetcher.scheduled() (service_binding_extra_handlers).
  async scheduled(controller, env) {
    const r = await env.__TW_PY.scheduled({ cron: controller.cron, scheduledTime: new Date(controller.scheduledTime) });
    if (r?.noRetry) controller.noRetry();
    if (r?.outcome !== "ok") throw new Error("the Python scheduled() handler failed (" + String(r?.outcome) + "); its exception is in the workload's logs");
  },
  // A queue batch: the Python default export's queue(), then what it decided
  // (ack, retry, per message or for the batch) replayed onto this batch.
  async queue(batch, env) {
    const msgs = batch.messages.map((m) => ({ id: m.id, timestamp: m.timestamp, body: m.body, attempts: m.attempts }));
    const r = await env.__TW_PY.queue(batch.queue, msgs);
    const byId = new Map(batch.messages.map((m) => [m.id, m]));
    for (const id of r?.explicitAcks ?? []) byId.get(id)?.ack();
    for (const m of r?.retryMessages ?? []) byId.get(m.msgId)?.retry(m.delaySeconds === undefined ? undefined : { delaySeconds: m.delaySeconds });
    if (r?.ackAll) batch.ackAll();
    if (r?.retryBatch?.retry) batch.retryAll(r.retryBatch.delaySeconds === undefined ? undefined : { delaySeconds: r.retryBatch.delaySeconds });
    if (r?.outcome !== "ok") throw new Error("the Python queue() handler failed (" + String(r?.outcome) + "); its exception is in the workload's logs");
  },
  // An RPC call over a service binding, after the binding dispatcher has
  // sealed its caller (runtime.ts): TailworksRpc.call() in tenant-py
  // (pyrpc.go) runs the method on the entrypoint's class.
  [Symbol.for("tailworks.pyRpc")](env, entrypoint, method, args, cf) {
    return env.__TW_PY_RPC.call(entrypoint, method, args, JSON.stringify(cf));
  },
};
`

// pythonFront is the app as the front sees it: the generated front module
// as its only module, and no Durable Objects (they live in tenant-py).
// Stores, services and vars stay: the platform serves the stores and
// service bindings, and tw-config.json lists them.
func pythonFront(app *bundle.App) *bundle.App {
	f := *app
	f.Python = false
	f.Main = pythonFrontModule
	f.Modules = map[string][]byte{pythonFrontModule: []byte(pythonFrontJS)}
	f.ModuleTypes = nil
	f.SourceMaps = nil
	f.Bindings = nil
	f.Classes = map[string]*bundle.Class{}
	f.CompatFlags = nil
	for _, fl := range app.CompatFlags {
		if !strings.HasPrefix(fl, "python_") && fl != "disable_python_external_sdk" && fl != extraHandlersFlag {
			f.CompatFlags = append(f.CompatFlags, fl)
		}
	}
	if len(app.Crons) > 0 || hasQueueConsumers(app) {
		// The front calls tenant-py's scheduled() and queue(): generated
		// code, so the flag is the platform's to set, as on its own worker.
		f.CompatFlags = append(f.CompatFlags, extraHandlersFlag)
	}
	return &f
}

// extraHandlersFlag lets a service binding call scheduled() and queue().
const extraHandlersFlag = "service_binding_extra_handlers"

// pythonService is tenant-py's entry in the config's services.
func pythonService(py *bundle.App) string {
	if !py.Python {
		return ""
	}
	return "    (name = \"tenant-py\", worker = .tenantPy),\n"
}

// pythonFrontBinding is the front's binding to tenant-py.
func pythonFrontBinding(py *bundle.App) string {
	if !py.Python {
		return ""
	}
	return "    (name = \"__TW_PY\", service = \"tenant-py\"),\n" + pythonFrontRPCBinding() // pyrpc.go
}

// pythonModuleKind is p's workerd module type in tenant-py.
func pythonModuleKind(py *bundle.App, p string) string {
	switch py.ModuleKind(p) {
	case "py":
		return "pythonModule"
	case "js":
		return "esModule"
	case "json":
		return "json"
	case "text":
		return "text"
	case "wasm":
		return "wasm"
	}
	return "data"
}

// writePython writes tenant-py's modules (py/<name>) and returns its
// worker definition.
func writePython(py *bundle.App, workload string, write func(string, []byte) error) (string, error) {
	if !py.Python {
		return "", nil
	}
	mods := make([]string, 0, len(py.Modules))
	for p := range py.Modules {
		if p != py.Main {
			mods = append(mods, p)
		}
	}
	sort.Strings(mods)
	mods = append([]string{py.Main}, mods...)
	main, err := pyMain(py) // pyrpc.go: workerd's main module (the first) re-exports py.Main
	if err != nil {
		return "", err
	}
	var c strings.Builder
	fmt.Fprintf(&c, "const tenantPy :Workerd.Worker = (\n  compatibilityDate = %s,\n  compatibilityFlags = [", cq(py.CompatDate))
	for i, f := range py.CompatFlags {
		if i > 0 {
			c.WriteString(", ")
		}
		c.WriteString(cq(f))
	}
	c.WriteString("],\n  modules = [\n")
	if err := write("py/"+pyMainModule, main); err != nil {
		return "", err
	}
	fmt.Fprintf(&c, "    (name = %s, pythonModule = embed %s),\n", cq(pyMainModule), cq("py/"+pyMainModule))
	for _, p := range mods {
		name := py.PythonModuleName(p)
		if name == "" {
			return "", fmt.Errorf("gen: module %s is outside the Python main module's directory", p)
		}
		if err := write("py/"+name, py.Modules[p]); err != nil {
			return "", err
		}
		fmt.Fprintf(&c, "    (name = %s, %s = embed %s),\n", cq(name), pythonModuleKind(py, p), cq("py/"+name))
	}
	c.WriteString("  ],\n  durableObjectNamespaces = [\n")
	for _, cl := range py.ClassNames() {
		fmt.Fprintf(&c, "    (className = %s, uniqueKey = %s, enableSql = true),\n", cq(cl), cq("tw-"+workload+"-"+cl))
	}
	c.WriteString("  ],\n  durableObjectStorage = (localDisk = \"do-storage\"),\n  bindings = [\n")
	for _, b := range py.Bindings {
		fmt.Fprintf(&c, "    (name = %s, durableObjectNamespace = %s),\n", cq(b.Name), cq(b.Class))
	}
	vars := make([]string, 0, len(py.Vars))
	for k := range py.Vars {
		vars = append(vars, k)
	}
	sort.Strings(vars)
	for _, k := range vars {
		if _, secret := py.Secrets[k]; secret {
			continue // the secret's text binding below overrides the var
		}
		fmt.Fprintf(&c, "    (name = %s, json = %s),\n", cq(k), cq(string(py.Vars[k])))
	}
	c.WriteString(secretBindings(py))
	c.WriteString(storeTenantBindings(py))
	c.WriteString(serviceTenantBindings(py)) // services.go
	c.WriteString(queueTenantBindings(py))   // queues.go: producers
	if py.Assets != nil && py.Assets.Binding != "" {
		// env.ASSETS: the assets router, as in a JavaScript tenant (assets.go).
		fmt.Fprintf(&c, "    (name = %s, service = \"assets\"),\n", cq(py.Assets.Binding))
	}
	c.WriteString("  ],\n  globalOutbound = (name = \"platform\", entrypoint = \"WorkloadEgress\"),\n" + tailsLine + ");\n\n")
	return c.String(), nil
}
